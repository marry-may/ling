/** Russian plural: 1 книга, 2 книги, 5 книг. */
const p = (n: number, one: string, few: string, many: string) => {
  const last = n % 10
  const lastTwo = n % 100
  if (lastTwo >= 11 && lastTwo <= 14) return many
  if (last === 1) return one
  if (last >= 2 && last <= 4) return few
  return many
}

